"""[F] Launch / watch F3 SFT runs as Kaggle script kernels (GPU T4 x2, DDP via torchrun).

Each run is one Kaggle kernel `<user>/desi-agent-<run>` that clones this repo at `--branch`, builds the
same py3.12 + torch env as our HF Jobs, and runs `scripts/train_sft.py` under torchrun on every GPU.
Checkpoints go to ToolW/desi-agent-training-logs every save_steps, so a run that hits Kaggle's 12 h
limit continues with `push --run X --resume` on any account (same run name = same checkpoint).

    python scripts/train_kaggle.py push --run sft-a -- --epochs 2 --push-to ToolW/desi-agent-tinyaya-sft-lora
    python scripts/train_kaggle.py push --run sft-a --resume -- <same args>     # next session
    python scripts/train_kaggle.py status --run sft-a
    python scripts/train_kaggle.py logs --run sft-a [--tail 40]
    python scripts/train_kaggle.py quota

HF token inside the kernel: Kaggle secret `HF_TOKEN` if attached, else the file `hf_token` from a
**private** Kaggle dataset (`--token-dataset`, default `<user>/desi-agent-hf-token`). Never in the repo.
Kaggle auth: ~/.kaggle/access_token (or KAGGLE_API_TOKEN). Each account launches its own runs.
"""
from __future__ import annotations

import argparse
import json
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
REPO_URL = "https://github.com/CyberRik/desi-agent.git"
CKPT_REPO = "ToolW/desi-agent-training-logs"
DATASET = "ToolW/desi-bank-toolcalls"

KERNEL_SRC = r'''# [F] desi-agent F3 run {run!r}, generated by scripts/train_kaggle.py. Do not edit on Kaggle.
import glob, os, subprocess, sys, time
RUN, BRANCH, ARGS, ENTRY = {run!r}, {branch!r}, {args!r}, {entry!r}
t0 = time.time()

def sh(cmd, **kw):
    print("+", cmd if isinstance(cmd, str) else " ".join(cmd), flush=True)
    subprocess.run(cmd, shell=isinstance(cmd, str), check=True, **kw)

token = None
try:
    from kaggle_secrets import UserSecretsClient
    token = UserSecretsClient().get_secret("HF_TOKEN")
except Exception:
    pass
if not token:
    files = glob.glob("/kaggle/input/**/hf_token", recursive=True)
    token = open(files[0]).read().strip() if files else None
if not token:
    sys.exit("[F] no HF token: attach Kaggle secret HF_TOKEN or the private token dataset")
env = dict(os.environ, HF_TOKEN=token, DESI_HF_DATASET={dataset!r}, PYTHONUNBUFFERED="1",
           TOKENIZERS_PARALLELISM="false")

W = "/tmp/desi-agent"
sh(["git", "clone", "-q", "-b", BRANCH, {repo_url!r}, W])
sh(["git", "-C", W, "log", "--oneline", "-1"])
sh("pip install -q uv")
sh("env -u UV_SYSTEM_PYTHON -u UV_PYTHON uv venv -q -p 3.12 --python-preference managed /tmp/venv")
sh("uv pip install --python /tmp/venv/bin/python -q --index-strategy unsafe-best-match "
   "--extra-index-url https://download.pytorch.org/whl/cu126 torch==2.11.0 -e '.[train]'", cwd=W)
py = "/tmp/venv/bin/python"
sh([py, "-c", "import torch, transformers, peft, agenttune; print(torch.__version__, transformers.__version__, "
    "peft.__version__, 'gpus', torch.cuda.device_count())"])
ngpu = int(subprocess.run([py, "-c", "import torch; print(torch.cuda.device_count())"],
                          capture_output=True, text=True).stdout.strip() or 0)
print(f"[F] setup done in {{time.time() - t0:.0f}}s, {{ngpu}} GPU(s)", flush=True)
if ENTRY == "scripts/train_sft.py":
    cmd = ([py, "-m", "torch.distributed.run", "--nproc_per_node", str(ngpu)] if ngpu > 1 else [py])
    cmd += [ENTRY, "--out", f"outputs/{{RUN}}", "--set", f"run_name={{RUN}}", "--set", "ckpt_repo={ckpt_repo}", *ARGS]
else:  # any other script, single process
    cmd = [py, ENTRY, "--out", f"outputs/{{RUN}}", *ARGS]
try:
    sh(cmd, cwd=W, env=env)
finally:
    os.makedirs("/kaggle/working/out", exist_ok=True)
    for f in ("manifest.json", "log_history.json"):
        p = f"{{W}}/outputs/{{RUN}}/{{f}}"
        if os.path.exists(p):
            sh(["cp", p, "/kaggle/working/out/"])
    print(f"[F] kernel finished in {{(time.time() - t0) / 3600:.2f}} h", flush=True)
'''


def kaggle(*args: str, capture: bool = False) -> str:
    exe = Path(sys.executable).with_name("kaggle")
    r = subprocess.run([str(exe) if exe.exists() else "kaggle", *args], capture_output=capture, text=True)
    if r.returncode:
        sys.exit(f"kaggle {' '.join(args)} failed:\n{(r.stdout or '') + (r.stderr or '')}")
    return r.stdout or ""


def api():
    from kaggle.api.kaggle_api_extended import KaggleApi
    a = KaggleApi()
    a.authenticate()
    return a


def whoami() -> str:
    return api().get_config_value("username")


def kernel_id(run: str, user: str | None) -> str:
    return f"{user or whoami()}/desi-agent-{run}"


def cmd_push(a) -> None:
    user = a.user or whoami()
    args = list(a.train_args)
    if args[:1] == ["--"]:
        args = args[1:]
    if "--out" in args or any(x.startswith(("run_name=", "ckpt_repo=")) for x in args):
        sys.exit("--out / run_name / ckpt_repo are set by the launcher")
    if a.entry != "scripts/train_sft.py":
        a.resume, a.hours = False, None
    if a.resume:
        args += ["--set", "resume=true"]
    if a.hours:
        args += ["--set", f"max_hours={a.hours}"]
    src = KERNEL_SRC.format(run=a.run, branch=a.branch, args=args, entry=a.entry, dataset=DATASET, repo_url=REPO_URL,
                            ckpt_repo=CKPT_REPO)
    compile(src, "run.py", "exec")
    meta = {"id": f"{user}/desi-agent-{a.run}", "title": f"desi-agent-{a.run}", "code_file": "run.py",
            "language": "python", "kernel_type": "script", "is_private": True, "enable_gpu": True,
            "enable_internet": True, "dataset_sources": [a.token_dataset or f"{user}/desi-agent-hf-token"],
            "competition_sources": [], "kernel_sources": [], "model_sources": []}
    with tempfile.TemporaryDirectory() as d:
        Path(d, "run.py").write_text(src)
        Path(d, "kernel-metadata.json").write_text(json.dumps(meta, indent=1))
        if a.dry_run:
            print(json.dumps(meta, indent=1)); print(src); return
        print(kaggle("kernels", "push", "-p", d, "--accelerator", a.accelerator, capture=True).strip())
    print(f"[F] pushed {meta['id']} (branch {a.branch}, args {args})")


def cmd_status(a) -> None:
    print(kaggle("kernels", "status", kernel_id(a.run, a.user), capture=True).strip())


def cmd_logs(a) -> None:
    with tempfile.TemporaryDirectory() as d:
        kaggle("kernels", "output", kernel_id(a.run, a.user), "-p", d, capture=True)
        logs = sorted(Path(d).glob("*.log"))
        if not logs:
            print("(no log yet; Kaggle only exposes output after the kernel finishes)")
        for p in logs:
            text = p.read_text(errors="replace")
            try:  # Kaggle logs are a JSON list of {"stream_name", "time", "data"}
                text = "".join(e.get("data", "") for e in json.loads(text))
            except ValueError:
                pass
            lines = [l for l in text.splitlines() if "warn" not in l.lower()]
            print("\n".join(lines[-a.tail:]))
        for p in sorted(Path(d).rglob("*.json")):
            if p.name in ("manifest.json", "log_history.json") and a.save:
                dest = ROOT / "outputs" / "kaggle" / a.run / p.name
                dest.parent.mkdir(parents=True, exist_ok=True)
                dest.write_text(p.read_text())
                print(f"[F] saved {dest.relative_to(ROOT)}")


def cmd_quota(a) -> None:
    api().quota_view_cli()


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)
    p = sub.add_parser("push")
    p.add_argument("--run", required=True, help="run name: kernel slug suffix and checkpoint folder")
    p.add_argument("--branch", default="main")
    p.add_argument("--user", help="Kaggle username (default: the authenticated one)")
    p.add_argument("--token-dataset", help="private Kaggle dataset holding `hf_token`")
    p.add_argument("--accelerator", default="NvidiaTeslaT4", help="NvidiaTeslaT4 = GPU T4 x2")
    p.add_argument("--hours", type=float, default=11.0, help="train time budget before checkpoint + stop")
    p.add_argument("--resume", action="store_true", help="continue from the run's HF checkpoint")
    p.add_argument("--dry-run", action="store_true")
    p.add_argument("--entry", default="scripts/train_sft.py", help="script to run (others run single-process)")
    p.add_argument("train_args", nargs=argparse.REMAINDER, help="-- then scripts/train_sft.py args")
    p.set_defaults(f=cmd_push)
    for name, f in (("status", cmd_status), ("logs", cmd_logs)):
        q = sub.add_parser(name)
        q.add_argument("--run", required=True)
        q.add_argument("--user")
        if name == "logs":
            q.add_argument("--tail", type=int, default=40)
            q.add_argument("--save", action="store_true", help="copy manifest/log_history to outputs/kaggle/<run>/")
        q.set_defaults(f=f)
    sub.add_parser("quota").set_defaults(f=cmd_quota)
    a = ap.parse_args()
    a.f(a)


if __name__ == "__main__":
    main()
